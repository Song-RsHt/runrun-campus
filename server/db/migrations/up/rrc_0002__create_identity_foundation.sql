-- M01 identity foundation. M00 owns the runrun_v2 namespace; this migration
-- creates only M01 objects and never reads legacy public tables.
BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = 'runrun_v2') THEN
    RAISE EXCEPTION 'M01 requires the M00 runrun_v2 schema';
  END IF;
  IF EXISTS (
    SELECT 1 FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'runrun_v2'
      AND c.relkind IN ('r','p','v','m','S','f')
  ) THEN
    RAISE EXCEPTION 'M01 requires an empty runrun_v2 schema before rrc_0002';
  END IF;
END
$$;

CREATE TABLE runrun_v2.app_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone TEXT NOT NULL,
  password_hash TEXT,
  role TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'ACTIVE',
  v2_admin_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  v2_admin_security_version BIGINT NOT NULL DEFAULT 0,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT app_users_phone_uq UNIQUE (phone),
  CONSTRAINT app_users_role_ck CHECK (role IN ('USER','COURIER','ADMIN')),
  CONSTRAINT app_users_status_ck CHECK (status IN ('ACTIVE','SUSPENDED','DELETED')),
  CONSTRAINT app_users_security_version_ck CHECK (v2_admin_security_version >= 0),
  CONSTRAINT app_users_version_ck CHECK (version >= 0)
);

CREATE TABLE runrun_v2.wechat_identities (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES runrun_v2.app_users(id),
  app_id TEXT NOT NULL,
  openid_ciphertext TEXT NOT NULL,
  openid_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT wechat_identities_app_openid_uq UNIQUE (app_id, openid_hash),
  CONSTRAINT wechat_identities_app_user_uq UNIQUE (app_id, user_id)
);

CREATE TABLE runrun_v2.user_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES runrun_v2.app_users(id),
  token_hash TEXT NOT NULL UNIQUE,
  issued_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at TIMESTAMPTZ NOT NULL,
  invalidated_at TIMESTAMPTZ,
  security_version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT user_sessions_security_version_ck CHECK (security_version >= 0)
);

CREATE TABLE runrun_v2.courier_certifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  courier_id BIGINT NOT NULL REFERENCES runrun_v2.app_users(id),
  status TEXT NOT NULL DEFAULT 'NOT_APPLIED',
  eligible BOOLEAN NOT NULL DEFAULT FALSE,
  submitted_photo_resource_id TEXT,
  submitted_photo_storage_key TEXT,
  approved_photo_resource_id TEXT,
  approved_photo_storage_key TEXT,
  rejection_reason TEXT,
  submitted_at TIMESTAMPTZ,
  reviewed_at TIMESTAMPTZ,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT courier_certifications_courier_uq UNIQUE (courier_id),
  CONSTRAINT courier_certifications_status_ck CHECK (status IN ('NOT_APPLIED','PENDING','APPROVED','REJECTED')),
  CONSTRAINT courier_certifications_version_ck CHECK (version >= 0),
  CONSTRAINT courier_certifications_submitted_photo_pair_ck CHECK ((submitted_photo_resource_id IS NULL) = (submitted_photo_storage_key IS NULL)),
  CONSTRAINT courier_certifications_approved_photo_pair_ck CHECK ((approved_photo_resource_id IS NULL) = (approved_photo_storage_key IS NULL))
);

CREATE UNIQUE INDEX courier_certifications_submitted_resource_uq
  ON runrun_v2.courier_certifications(submitted_photo_resource_id)
  WHERE submitted_photo_resource_id IS NOT NULL;
CREATE UNIQUE INDEX courier_certifications_approved_resource_uq
  ON runrun_v2.courier_certifications(approved_photo_resource_id)
  WHERE approved_photo_resource_id IS NOT NULL;

CREATE TABLE runrun_v2.courier_certification_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  certification_id BIGINT NOT NULL REFERENCES runrun_v2.courier_certifications(id),
  actor_id BIGINT REFERENCES runrun_v2.app_users(id),
  actor_kind TEXT NOT NULL,
  event_type TEXT NOT NULL,
  request_id TEXT NOT NULL,
  certification_version BIGINT NOT NULL,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT certification_events_actor_kind_ck CHECK (actor_kind IN ('COURIER','ADMIN','SYSTEM')),
  CONSTRAINT certification_events_system_actor_ck CHECK (actor_kind <> 'SYSTEM' OR actor_id IS NULL),
  CONSTRAINT certification_events_actor_required_ck CHECK (actor_kind = 'SYSTEM' OR actor_id IS NOT NULL),
  CONSTRAINT certification_events_version_ck CHECK (certification_version >= 0),
  CONSTRAINT certification_events_request_uq UNIQUE (certification_id, event_type, request_id)
);

CREATE TABLE runrun_v2.admin_audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id BIGINT NOT NULL REFERENCES runrun_v2.app_users(id),
  action TEXT NOT NULL,
  target_type TEXT NOT NULL,
  target_id BIGINT,
  request_id TEXT NOT NULL,
  reason TEXT NOT NULL,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT admin_audit_request_uq UNIQUE (actor_id, action, request_id)
);

CREATE TABLE runrun_v2.idempotency_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id BIGINT NOT NULL REFERENCES runrun_v2.app_users(id),
  scope TEXT NOT NULL,
  key TEXT NOT NULL,
  request_hash TEXT NOT NULL,
  status TEXT NOT NULL,
  resource_type TEXT,
  resource_id TEXT,
  response_snapshot JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT idempotency_requests_uq UNIQUE (actor_id, scope, key),
  CONSTRAINT idempotency_requests_status_ck CHECK (status IN ('PROCESSING','SUCCEEDED','FAILED'))
);

CREATE TABLE runrun_v2.notification_outbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient_id BIGINT NOT NULL REFERENCES runrun_v2.app_users(id),
  event_key TEXT NOT NULL,
  channel TEXT NOT NULL,
  payload JSONB NOT NULL,
  status TEXT NOT NULL DEFAULT 'PENDING',
  attempt_count INTEGER NOT NULL DEFAULT 0,
  next_attempt_at TIMESTAMPTZ,
  last_error TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT notification_outbox_event_uq UNIQUE (event_key, recipient_id, channel),
  CONSTRAINT notification_outbox_channel_ck CHECK (channel IN ('IN_APP','WECHAT')),
  CONSTRAINT notification_outbox_status_ck CHECK (status IN ('PENDING','SENDING','SENT','FAILED')),
  CONSTRAINT notification_outbox_attempt_ck CHECK (attempt_count >= 0)
);

CREATE INDEX user_sessions_user_active_idx ON runrun_v2.user_sessions(user_id, invalidated_at, expires_at);
CREATE INDEX courier_certifications_status_idx ON runrun_v2.courier_certifications(status, submitted_at, id);
CREATE INDEX certification_events_cert_created_idx ON runrun_v2.courier_certification_events(certification_id, created_at, id);
CREATE INDEX admin_audit_target_idx ON runrun_v2.admin_audit_logs(target_type, target_id, created_at, id);
CREATE INDEX idempotency_requests_resource_idx ON runrun_v2.idempotency_requests(resource_type, resource_id);
CREATE INDEX notification_outbox_pending_idx ON runrun_v2.notification_outbox(status, next_attempt_at, created_at, id);

COMMENT ON TABLE runrun_v2.app_users IS 'M01 v2 account root; no legacy public account rows are imported.';
COMMENT ON COLUMN runrun_v2.courier_certifications.eligible IS 'Current接单资格独立于申请审核状态; photo deletion does not revoke it.';
COMMIT;
