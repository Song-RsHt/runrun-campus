CREATE FUNCTION v2_fixed_flow() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.order_flow_version IS DISTINCT FROM OLD.order_flow_version THEN
        RAISE EXCEPTION 'order_flow_version is immutable' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END $$;
