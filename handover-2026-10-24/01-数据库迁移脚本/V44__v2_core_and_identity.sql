-- Legacy writers must invalidate a v2 preview as well; Hibernate's explicit +1 is accepted once.
CREATE FUNCTION v2_increment_version() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.version <> 0 THEN RAISE EXCEPTION 'initial version must be zero' USING ERRCODE='23514'; END IF;
    ELSE
        IF NEW.version = OLD.version THEN NEW.version := OLD.version + 1;
        ELSIF NEW.version <> OLD.version + 1 THEN
            RAISE EXCEPTION 'version must increase by one' USING ERRCODE='23514';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER certification_version BEFORE INSERT OR UPDATE ON courier_certifications
    FOR EACH ROW EXECUTE FUNCTION v2_increment_version();
CREATE FUNCTION v2_certification_resources() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.submitted_photo_key IS NULL THEN NEW.submitted_photo_resource_id := NULL;
    ELSIF TG_OP = 'INSERT' OR NEW.submitted_photo_key IS DISTINCT FROM OLD.submitted_photo_key THEN
        NEW.submitted_photo_resource_id := 'photo-' || md5(random()::text || clock_timestamp()::text || NEW.id::text);
    END IF;
    IF NEW.approved_photo_key IS NULL THEN NEW.approved_photo_resource_id := NULL;
    ELSIF TG_OP = 'INSERT' OR NEW.approved_photo_key IS DISTINCT FROM OLD.approved_photo_key THEN
        IF TG_OP = 'UPDATE' AND NEW.approved_photo_key = OLD.submitted_photo_key THEN
            NEW.approved_photo_resource_id := OLD.submitted_photo_resource_id;
        ELSE NEW.approved_photo_resource_id := 'photo-' || md5(random()::text || clock_timestamp()::text || NEW.id::text);
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER certification_resources BEFORE INSERT OR UPDATE ON courier_certifications
    FOR EACH ROW EXECUTE FUNCTION v2_certification_resources();
