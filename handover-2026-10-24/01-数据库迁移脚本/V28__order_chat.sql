CREATE TABLE order_chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES campus_orders(id),
    sender_id BIGINT NOT NULL REFERENCES app_users(id),
    recipient_id BIGINT NOT NULL REFERENCES app_users(id),
    content VARCHAR(500) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_order_chat_order_created ON order_chat_messages (order_id, created_at, id);

ALTER TABLE order_messages DROP CONSTRAINT order_messages_type_check;
ALTER TABLE order_messages ADD CONSTRAINT order_messages_type_check CHECK (type IN (
    'ORDER_ACCEPTED', 'ORDER_PICKED_UP', 'ORDER_COMPLETED', 'ORDER_ISSUE', 'ORDER_CHAT',
    'PACKAGE_SIZE_CHANGE_REQUESTED', 'PACKAGE_SIZE_CHANGE_APPROVED', 'PACKAGE_SIZE_CHANGE_REJECTED'
));
