CREATE TABLE admin_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action VARCHAR(40) NOT NULL,
    target_type VARCHAR(40) NOT NULL,
    target_id BIGINT NOT NULL,
    summary VARCHAR(300) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    administrator_id BIGINT NOT NULL REFERENCES app_users(id),
    CONSTRAINT admin_audit_logs_action_check CHECK (action IN ('COURIER_CERTIFICATION_APPROVED', 'COURIER_CERTIFICATION_REJECTED')),
    CONSTRAINT admin_audit_logs_target_type_check CHECK (target_type IN ('COURIER_CERTIFICATION'))
);

CREATE INDEX idx_admin_audit_logs_created ON admin_audit_logs (created_at DESC);
CREATE INDEX idx_admin_audit_logs_administrator_created ON admin_audit_logs (administrator_id, created_at DESC);
