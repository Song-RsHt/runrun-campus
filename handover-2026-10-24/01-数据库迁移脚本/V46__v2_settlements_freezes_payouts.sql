-- C M46: immutable financial facts; mutable decisions are separate aggregates.
CREATE TABLE settlement_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), order_id BIGINT NOT NULL REFERENCES v2_orders,
    beneficiary_type TEXT NOT NULL CHECK (beneficiary_type IN ('PLATFORM','COURIER')),
    beneficiary_id BIGINT REFERENCES app_users, task_id BIGINT,
    source_type TEXT NOT NULL, source_id TEXT NOT NULL, kind TEXT NOT NULL,
    delta_cents BIGINT NOT NULL, reason TEXT NOT NULL CHECK (btrim(reason) <> ''),
    CHECK ((beneficiary_type = 'PLATFORM' AND beneficiary_id IS NULL) OR (beneficiary_type = 'COURIER' AND beneficiary_id IS NOT NULL)),
    FOREIGN KEY(order_id,task_id) REFERENCES fulfillment_tasks(order_id,id),
    UNIQUE NULLS NOT DISTINCT(source_type,source_id,beneficiary_type,beneficiary_id,kind)
);
CREATE INDEX idx_settlement_order_subject ON settlement_entries(order_id,beneficiary_type,beneficiary_id);
CREATE INDEX idx_settlement_beneficiary ON settlement_entries(beneficiary_id);
CREATE INDEX idx_settlement_task ON settlement_entries(order_id,task_id);
CREATE TRIGGER settlement_append_only BEFORE UPDATE OR DELETE ON settlement_entries FOR EACH ROW EXECUTE FUNCTION v2_append_only();

CREATE TABLE rider_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    order_id BIGINT NOT NULL REFERENCES v2_orders, allocation_version INTEGER NOT NULL CHECK (allocation_version > 0),
    status TEXT NOT NULL CHECK (status IN ('DRAFT','APPROVED','SUPERSEDED')),
    automatic BOOLEAN NOT NULL, approved_by BIGINT REFERENCES app_users, reason TEXT NOT NULL CHECK (btrim(reason) <> ''),
    UNIQUE(order_id,allocation_version)
);
CREATE UNIQUE INDEX uk_allocation_current ON rider_allocations(order_id) WHERE status = 'APPROVED';
CREATE INDEX idx_allocation_admin ON rider_allocations(approved_by);
CREATE TABLE rider_allocation_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), allocation_id BIGINT NOT NULL REFERENCES rider_allocations,
    task_id BIGINT NOT NULL REFERENCES fulfillment_tasks, courier_id BIGINT NOT NULL REFERENCES app_users,
    amount_cents BIGINT NOT NULL CHECK (amount_cents >= 0), UNIQUE(allocation_id,task_id,courier_id),
    FOREIGN KEY(task_id,courier_id) REFERENCES fulfillment_tasks(id,courier_id)
);
-- The allocation has no order_id in C; enforce its task's order without adding an API field.
CREATE FUNCTION v2_allocation_same_order() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    -- Hold parents while checking, so a concurrent parent update cannot invalidate the assertion.
    PERFORM 1 FROM rider_allocations a JOIN fulfillment_tasks t ON t.order_id=a.order_id
        WHERE a.id=NEW.allocation_id AND t.id=NEW.task_id FOR SHARE OF a,t;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'allocation task belongs to another order' USING ERRCODE='23503';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER allocation_same_order BEFORE INSERT OR UPDATE ON rider_allocation_lines FOR EACH ROW EXECUTE FUNCTION v2_allocation_same_order();
CREATE FUNCTION v2_allocation_parent_order() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.order_id IS DISTINCT FROM OLD.order_id THEN
        IF TG_TABLE_NAME = 'rider_allocations' THEN
            IF EXISTS (SELECT 1 FROM rider_allocation_lines l JOIN fulfillment_tasks t ON t.id=l.task_id
                WHERE l.allocation_id=OLD.id AND t.order_id<>NEW.order_id) THEN
                RAISE EXCEPTION 'allocation order conflicts with existing lines' USING ERRCODE='23503';
            END IF;
        ELSE
            IF EXISTS (SELECT 1 FROM rider_allocation_lines l JOIN rider_allocations a ON a.id=l.allocation_id
                WHERE l.task_id=OLD.id AND a.order_id<>NEW.order_id) THEN
                RAISE EXCEPTION 'task order conflicts with existing allocation' USING ERRCODE='23503';
            END IF;
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER allocation_parent_order BEFORE UPDATE ON rider_allocations FOR EACH ROW EXECUTE FUNCTION v2_allocation_parent_order();
CREATE TRIGGER allocation_task_order BEFORE UPDATE ON fulfillment_tasks FOR EACH ROW EXECUTE FUNCTION v2_allocation_parent_order();
CREATE INDEX idx_allocation_lines_task ON rider_allocation_lines(task_id,courier_id);
CREATE INDEX idx_allocation_lines_courier ON rider_allocation_lines(courier_id);

CREATE TABLE settlement_freezes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    order_id BIGINT NOT NULL REFERENCES v2_orders,
    beneficiary_type TEXT NOT NULL CHECK (beneficiary_type IN ('PLATFORM','COURIER')), beneficiary_id BIGINT REFERENCES app_users,
    source_type TEXT NOT NULL, source_id TEXT NOT NULL, frozen_cents BIGINT NOT NULL CHECK (frozen_cents >= 0),
    reason TEXT NOT NULL CHECK (btrim(reason) <> ''), released_at TIMESTAMPTZ,
    CHECK ((beneficiary_type = 'PLATFORM' AND beneficiary_id IS NULL) OR (beneficiary_type = 'COURIER' AND beneficiary_id IS NOT NULL))
);
CREATE INDEX idx_freezes_order_release ON settlement_freezes(order_id,released_at);
CREATE INDEX idx_freezes_beneficiary ON settlement_freezes(beneficiary_id);
CREATE TABLE freeze_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), freeze_id BIGINT NOT NULL REFERENCES settlement_freezes,
    event_type TEXT NOT NULL CHECK (event_type IN ('CREATED','RESIZED','RELEASED')),
    previous_cents BIGINT NOT NULL CHECK (previous_cents >= 0), new_cents BIGINT NOT NULL CHECK (new_cents >= 0),
    actor_id BIGINT REFERENCES app_users, reason TEXT NOT NULL CHECK (btrim(reason) <> '')
);
CREATE INDEX idx_freeze_events_time ON freeze_events(freeze_id,created_at);
CREATE INDEX idx_freeze_events_actor ON freeze_events(actor_id);
CREATE TRIGGER freeze_events_append_only BEFORE UPDATE OR DELETE ON freeze_events FOR EACH ROW EXECUTE FUNCTION v2_append_only();
CREATE TABLE payout_registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), order_id BIGINT NOT NULL REFERENCES v2_orders,
    beneficiary_type TEXT NOT NULL CHECK (beneficiary_type IN ('PLATFORM','COURIER')), beneficiary_id BIGINT REFERENCES app_users,
    amount_cents BIGINT NOT NULL CHECK (amount_cents > 0), mode TEXT NOT NULL DEFAULT 'MOCK' CHECK (mode='MOCK'),
    reference TEXT NOT NULL UNIQUE, reason TEXT NOT NULL CHECK (btrim(reason) <> ''),
    registered_by BIGINT NOT NULL REFERENCES app_users, registered_at TIMESTAMPTZ NOT NULL,
    CHECK ((beneficiary_type = 'PLATFORM' AND beneficiary_id IS NULL) OR (beneficiary_type = 'COURIER' AND beneficiary_id IS NOT NULL))
);
CREATE INDEX idx_payout_order ON payout_registrations(order_id);
CREATE INDEX idx_payout_beneficiary ON payout_registrations(beneficiary_id);
CREATE INDEX idx_payout_actor ON payout_registrations(registered_by);
CREATE TRIGGER payout_append_only BEFORE UPDATE OR DELETE ON payout_registrations FOR EACH ROW EXECUTE FUNCTION v2_append_only();
CREATE TRIGGER aggregate_version BEFORE INSERT OR UPDATE ON rider_allocations FOR EACH ROW EXECUTE FUNCTION v2_increment_version();
CREATE TRIGGER aggregate_version BEFORE INSERT OR UPDATE ON settlement_freezes FOR EACH ROW EXECUTE FUNCTION v2_increment_version();
