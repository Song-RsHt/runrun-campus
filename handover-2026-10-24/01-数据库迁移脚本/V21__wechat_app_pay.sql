CREATE TABLE wechat_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT,
    out_trade_no VARCHAR(32) NOT NULL,
    business_type VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL,
    amount_cents INTEGER NOT NULL,
    transaction_id VARCHAR(32),
    membership_plan VARCHAR(24),
    app_id VARCHAR(32),
    partner_id VARCHAR(32),
    prepay_id VARCHAR(64),
    package_value VARCHAR(32),
    nonce_str VARCHAR(64),
    pay_timestamp VARCHAR(32),
    pay_signature VARCHAR(512),
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    paid_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    order_id BIGINT REFERENCES campus_orders(id),
    CONSTRAINT uk_wechat_payments_out_trade_no UNIQUE (out_trade_no),
    CONSTRAINT uk_wechat_payments_transaction_id UNIQUE (transaction_id),
    CONSTRAINT wechat_payments_business_type_check CHECK (business_type IN ('ORDER', 'MEMBERSHIP')),
    CONSTRAINT wechat_payments_status_check CHECK (status IN ('PENDING', 'PAID', 'CLOSED')),
    CONSTRAINT wechat_payments_amount_check CHECK (amount_cents > 0),
    CONSTRAINT wechat_payments_target_check CHECK (
        (business_type = 'ORDER' AND order_id IS NOT NULL AND membership_plan IS NULL)
        OR (business_type = 'MEMBERSHIP' AND order_id IS NULL AND membership_plan IS NOT NULL)
    )
);

CREATE INDEX idx_wechat_payments_order ON wechat_payments(order_id);
CREATE INDEX idx_wechat_payments_user ON wechat_payments(user_id);
CREATE UNIQUE INDEX uk_wechat_payments_pending_membership
    ON wechat_payments(user_id)
    WHERE business_type = 'MEMBERSHIP' AND status = 'PENDING';

CREATE TABLE wechat_refunds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT,
    out_refund_no VARCHAR(32) NOT NULL,
    amount_cents INTEGER NOT NULL,
    status VARCHAR(16) NOT NULL,
    reason VARCHAR(80) NOT NULL,
    wechat_refund_id VARCHAR(32),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    payment_id BIGINT NOT NULL REFERENCES wechat_payments(id),
    CONSTRAINT uk_wechat_refunds_out_refund_no UNIQUE (out_refund_no),
    CONSTRAINT wechat_refunds_amount_check CHECK (amount_cents > 0),
    CONSTRAINT wechat_refunds_status_check CHECK (status IN ('PENDING', 'PROCESSING', 'SUCCESS'))
);

CREATE INDEX idx_wechat_refunds_payment ON wechat_refunds(payment_id);
CREATE INDEX idx_wechat_refunds_pending ON wechat_refunds(status, created_at);
