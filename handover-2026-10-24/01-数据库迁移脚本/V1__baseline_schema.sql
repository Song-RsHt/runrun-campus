CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    display_name VARCHAR(48) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    phone VARCHAR(32) NOT NULL,
    role VARCHAR(16) NOT NULL,
    courier_approved BOOLEAN,
    CONSTRAINT uk_app_users_phone UNIQUE (phone),
    CONSTRAINT app_users_role_check CHECK (role IN ('CUSTOMER', 'COURIER', 'ADMIN'))
);

CREATE TABLE campus_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    destination VARCHAR(120) NOT NULL,
    fee_cents INTEGER NOT NULL,
    merchant VARCHAR(80) NOT NULL,
    order_no VARCHAR(24) NOT NULL,
    pickup_code VARCHAR(32) NOT NULL,
    pickup_location VARCHAR(120) NOT NULL,
    service_type VARCHAR(16) NOT NULL,
    status VARCHAR(24) NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version BIGINT,
    courier_id BIGINT REFERENCES app_users(id),
    customer_id BIGINT NOT NULL REFERENCES app_users(id),
    courier_latitude DOUBLE PRECISION,
    courier_location_updated_at TIMESTAMP(6) WITH TIME ZONE,
    courier_longitude DOUBLE PRECISION,
    coupon_title VARCHAR(48),
    discount_cents INTEGER,
    original_fee_cents INTEGER,
    membership_plan_title VARCHAR(48),
    membership_used BOOLEAN,
    rated_at TIMESTAMP(6) WITH TIME ZONE,
    rating_comment VARCHAR(300),
    rating_score INTEGER,
    CONSTRAINT uk_campus_orders_order_no UNIQUE (order_no),
    CONSTRAINT campus_orders_service_type_check CHECK (service_type IN ('LOBBY', 'DOOR', 'EXPRESS')),
    CONSTRAINT campus_orders_status_check CHECK (status IN ('PENDING_ASSIGNMENT', 'ACCEPTED', 'PICKED_UP', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE courier_certifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campus VARCHAR(80) NOT NULL,
    real_name VARCHAR(48) NOT NULL,
    rejection_reason VARCHAR(300),
    reviewed_at TIMESTAMP(6) WITH TIME ZONE,
    status VARCHAR(24) NOT NULL,
    student_id VARCHAR(40) NOT NULL,
    submitted_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    courier_id BIGINT NOT NULL REFERENCES app_users(id),
    reviewer_id BIGINT REFERENCES app_users(id),
    CONSTRAINT uk_courier_certifications_courier UNIQUE (courier_id),
    CONSTRAINT courier_certifications_status_check CHECK (status IN ('NOT_APPLIED', 'PENDING', 'APPROVED', 'REJECTED'))
);

CREATE TABLE order_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    status VARCHAR(24) NOT NULL,
    actor_id BIGINT NOT NULL REFERENCES app_users(id),
    order_id BIGINT NOT NULL REFERENCES campus_orders(id),
    CONSTRAINT order_events_status_check CHECK (status IN ('PENDING_ASSIGNMENT', 'ACCEPTED', 'PICKED_UP', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE order_issues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    description VARCHAR(500) NOT NULL,
    issue_type VARCHAR(32) NOT NULL,
    order_id BIGINT NOT NULL REFERENCES campus_orders(id),
    reporter_id BIGINT NOT NULL REFERENCES app_users(id),
    CONSTRAINT order_issues_issue_type_check CHECK (issue_type IN ('MISSING_ITEM', 'WRONG_ORDER', 'CANNOT_CONTACT', 'DELIVERY_DELAY', 'OTHER'))
);

CREATE TABLE order_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content VARCHAR(600) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    read_at TIMESTAMP(6) WITH TIME ZONE,
    title VARCHAR(80) NOT NULL,
    type VARCHAR(32) NOT NULL,
    order_id BIGINT NOT NULL REFERENCES campus_orders(id),
    recipient_id BIGINT NOT NULL REFERENCES app_users(id),
    CONSTRAINT order_messages_type_check CHECK (type IN ('ORDER_ACCEPTED', 'ORDER_PICKED_UP', 'ORDER_COMPLETED', 'ORDER_ISSUE'))
);

CREATE TABLE order_proofs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_type VARCHAR(64) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    original_file_name VARCHAR(255) NOT NULL,
    size_bytes BIGINT NOT NULL,
    stored_file_name VARCHAR(160) NOT NULL,
    type VARCHAR(16) NOT NULL,
    order_id BIGINT NOT NULL REFERENCES campus_orders(id),
    uploader_id BIGINT NOT NULL REFERENCES app_users(id),
    CONSTRAINT uk_order_proof_order_type UNIQUE (order_id, type),
    CONSTRAINT uk_order_proofs_stored_file_name UNIQUE (stored_file_name),
    CONSTRAINT order_proofs_type_check CHECK (type IN ('PICKUP', 'DELIVERY'))
);

CREATE TABLE user_addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address VARCHAR(120) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    is_default BOOLEAN NOT NULL,
    label VARCHAR(32) NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    user_id BIGINT NOT NULL REFERENCES app_users(id)
);

CREATE TABLE user_coupons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    discount_cents INTEGER NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    minimum_order_cents INTEGER NOT NULL,
    title VARCHAR(48) NOT NULL,
    used_at TIMESTAMP(6) WITH TIME ZONE,
    version BIGINT,
    user_id BIGINT NOT NULL REFERENCES app_users(id)
);

CREATE TABLE user_feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content VARCHAR(500) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    type VARCHAR(24) NOT NULL,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    CONSTRAINT user_feedback_type_check CHECK (type IN ('FUNCTION', 'ACCOUNT', 'OTHER'))
);

CREATE TABLE user_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    plan VARCHAR(24) NOT NULL,
    price_cents INTEGER NOT NULL,
    purchased_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    remaining_trips INTEGER NOT NULL,
    total_trips INTEGER NOT NULL,
    version BIGINT,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    CONSTRAINT user_memberships_plan_check CHECK (plan IN ('LIGHT', 'STUDENT', 'ROOMMATE'))
);

CREATE TABLE user_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    token VARCHAR(128) NOT NULL,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    CONSTRAINT uk_user_sessions_token UNIQUE (token)
);
