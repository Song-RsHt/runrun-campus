CREATE TABLE fulfillment_provenance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_ref VARCHAR(80) NOT NULL UNIQUE,
    channel VARCHAR(24) NOT NULL,
    app_order_id BIGINT REFERENCES campus_orders(id),
    completed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    customer_paid_cents BIGINT,
    platform_revenue_cents BIGINT,
    courier_settlement_cents BIGINT,
    completion_evidence_sha256 CHAR(64) NOT NULL,
    financial_evidence_sha256 CHAR(64),
    recorded_by BIGINT NOT NULL REFERENCES app_users(id),
    recorded_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    verified_by BIGINT REFERENCES app_users(id),
    verified_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fulfillment_provenance_channel_check CHECK
        (channel IN ('APP_END_TO_END', 'APP_ASSISTED', 'MANUAL_OFFLINE')),
    CONSTRAINT fulfillment_provenance_source_check CHECK
        ((channel = 'APP_END_TO_END' AND app_order_id IS NOT NULL)
         OR (channel = 'APP_ASSISTED')
         OR (channel = 'MANUAL_OFFLINE' AND app_order_id IS NULL)),
    CONSTRAINT fulfillment_provenance_amounts_check CHECK
        (customer_paid_cents >= 0 AND platform_revenue_cents >= 0 AND courier_settlement_cents >= 0),
    CONSTRAINT fulfillment_provenance_verified_check CHECK
        ((verified_by IS NULL AND verified_at IS NULL)
         OR (verified_by IS NOT NULL AND verified_at IS NOT NULL AND verified_by <> recorded_by)),
    CONSTRAINT fulfillment_provenance_finance_check CHECK
        ((customer_paid_cents IS NULL AND platform_revenue_cents IS NULL AND courier_settlement_cents IS NULL)
         OR financial_evidence_sha256 IS NOT NULL)
);

CREATE UNIQUE INDEX uk_fulfillment_provenance_app_order
    ON fulfillment_provenance (app_order_id) WHERE app_order_id IS NOT NULL;
CREATE INDEX idx_fulfillment_provenance_completed
    ON fulfillment_provenance (completed_at DESC);
