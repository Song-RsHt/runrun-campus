-- C M47: transactional persistence is separate from best-effort external delivery.
CREATE TABLE user_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    user_id BIGINT NOT NULL REFERENCES app_users, order_id BIGINT REFERENCES v2_orders,
    type TEXT NOT NULL, content JSONB NOT NULL CHECK (jsonb_typeof(content)='object'), read_at TIMESTAMPTZ
);
CREATE INDEX idx_notifications_user_time ON user_notifications(user_id,created_at,id);
CREATE INDEX idx_notifications_order ON user_notifications(order_id);
CREATE TABLE notification_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    recipient_id BIGINT NOT NULL REFERENCES app_users, event_key TEXT NOT NULL,
    channel TEXT NOT NULL CHECK (channel IN ('IN_APP','WECHAT')),
    payload JSONB NOT NULL CHECK (jsonb_typeof(payload)='object'), status TEXT NOT NULL,
    attempt_count INTEGER NOT NULL CHECK (attempt_count >= 0), next_attempt_at TIMESTAMPTZ, last_error TEXT,
    UNIQUE(event_key,recipient_id,channel)
);
CREATE INDEX idx_outbox_recipient ON notification_outbox(recipient_id);
CREATE INDEX idx_outbox_retry ON notification_outbox(status,next_attempt_at,id);
CREATE TRIGGER aggregate_version BEFORE INSERT OR UPDATE ON user_notifications FOR EACH ROW EXECUTE FUNCTION v2_increment_version();
CREATE TRIGGER aggregate_version BEFORE INSERT OR UPDATE ON notification_outbox FOR EACH ROW EXECUTE FUNCTION v2_increment_version();
