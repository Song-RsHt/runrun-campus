-- C M45: original payments and each separate adjustment have different uniqueness scopes.
CREATE TABLE order_adjustments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    order_id BIGINT NOT NULL REFERENCES v2_orders, requested_by BIGINT NOT NULL REFERENCES app_users,
    spec_proof_id BIGINT, from_service_type TEXT NOT NULL, to_service_type TEXT NOT NULL,
    delta_cents BIGINT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('PENDING_REVIEW','PENDING_SUPPLEMENT','PENDING_REFUND','COMPLETED','REJECTED','CANCELLED','TRANSFERRED_TO_DEBT')),
    assigned_admin_id BIGINT REFERENCES app_users,
    requested_at TIMESTAMPTZ NOT NULL, remind_at TIMESTAMPTZ NOT NULL, escalate_at TIMESTAMPTZ NOT NULL,
    decided_at TIMESTAMPTZ, pay_deadline TIMESTAMPTZ, resolved_at TIMESTAMPTZ, decision_reason TEXT,
    UNIQUE(order_id,id), FOREIGN KEY(order_id,spec_proof_id) REFERENCES v2_order_proofs(order_id,id)
);
CREATE UNIQUE INDEX uk_adjustment_open ON order_adjustments(order_id)
    WHERE status IN ('PENDING_REVIEW','PENDING_SUPPLEMENT','PENDING_REFUND');
CREATE INDEX idx_adjustment_remind ON order_adjustments(status,remind_at);
CREATE INDEX idx_adjustment_escalate ON order_adjustments(status,escalate_at);
CREATE INDEX idx_adjustment_requester ON order_adjustments(requested_by);
CREATE INDEX idx_adjustment_admin ON order_adjustments(assigned_admin_id);
CREATE INDEX idx_adjustment_proof ON order_adjustments(order_id,spec_proof_id);

CREATE TABLE payment_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    order_id BIGINT NOT NULL REFERENCES v2_orders, adjustment_id BIGINT,
    purpose TEXT NOT NULL CHECK (purpose IN ('ORIGINAL','SUPPLEMENT')),
    amount_cents BIGINT NOT NULL CHECK (amount_cents >= 0),
    status TEXT NOT NULL CHECK (status IN ('UNPAID','PROCESSING','UNKNOWN','FAILED','PAID','CLOSED')),
    deadline TIMESTAMPTZ, paid_at TIMESTAMPTZ,
    CHECK ((purpose = 'ORIGINAL' AND adjustment_id IS NULL) OR (purpose = 'SUPPLEMENT' AND adjustment_id IS NOT NULL)),
    UNIQUE(order_id,id), FOREIGN KEY(order_id,adjustment_id) REFERENCES order_adjustments(order_id,id)
);
CREATE UNIQUE INDEX uk_payment_original ON payment_orders(order_id) WHERE purpose = 'ORIGINAL';
CREATE UNIQUE INDEX uk_payment_supplement ON payment_orders(adjustment_id) WHERE purpose = 'SUPPLEMENT';
CREATE INDEX idx_payment_adjustment ON payment_orders(order_id,adjustment_id);

CREATE TABLE payment_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    payment_order_id BIGINT NOT NULL REFERENCES payment_orders,
    attempt_no INTEGER NOT NULL CHECK (attempt_no > 0), status TEXT NOT NULL,
    channel_reference TEXT UNIQUE, result_received_at TIMESTAMPTZ,
    UNIQUE(payment_order_id,attempt_no)
);
CREATE UNIQUE INDEX uk_payment_attempt_inflight ON payment_attempts(payment_order_id) WHERE status IN ('PROCESSING','UNKNOWN');

CREATE TABLE refund_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    order_id BIGINT NOT NULL REFERENCES v2_orders, payment_order_id BIGINT NOT NULL, adjustment_id BIGINT, case_id BIGINT,
    amount_cents BIGINT NOT NULL CHECK (amount_cents > 0), purpose TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('REQUESTED','PROCESSING','UNKNOWN','FAILED','SUCCEEDED')),
    reason TEXT NOT NULL CHECK (btrim(reason) <> ''), channel_reference TEXT, succeeded_at TIMESTAMPTZ,
    FOREIGN KEY(order_id,payment_order_id) REFERENCES payment_orders(order_id,id),
    FOREIGN KEY(order_id,adjustment_id) REFERENCES order_adjustments(order_id,id),
    FOREIGN KEY(order_id,case_id) REFERENCES after_sales_cases(order_id,id)
);
CREATE INDEX idx_refund_payment_status ON refund_orders(payment_order_id,status);
CREATE INDEX idx_refund_order_payment ON refund_orders(order_id,payment_order_id);
CREATE INDEX idx_refund_adjustment ON refund_orders(order_id,adjustment_id);
CREATE INDEX idx_refund_case ON refund_orders(order_id,case_id);

CREATE TABLE debts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    order_id BIGINT NOT NULL REFERENCES v2_orders, debtor_id BIGINT NOT NULL REFERENCES app_users,
    source_type TEXT NOT NULL, source_id TEXT NOT NULL,
    principal_cents BIGINT NOT NULL CHECK (principal_cents >= 0),
    outstanding_cents BIGINT NOT NULL CHECK (outstanding_cents >= 0 AND outstanding_cents <= principal_cents),
    status TEXT NOT NULL CHECK (status IN ('OPEN','SETTLED','WAIVED','RECOVERY_STOPPED')),
    reason TEXT NOT NULL CHECK (btrim(reason) <> ''), closed_at TIMESTAMPTZ
);
CREATE INDEX idx_debts_order ON debts(order_id);
CREATE INDEX idx_debts_debtor_status ON debts(debtor_id,status);
CREATE TABLE debt_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), debt_id BIGINT NOT NULL REFERENCES debts,
    kind TEXT NOT NULL CHECK (kind IN ('REPAYMENT','WAIVER','STOP_RECOVERY')),
    amount_cents BIGINT NOT NULL CHECK (amount_cents >= 0), reason TEXT NOT NULL CHECK (btrim(reason) <> ''),
    actor_id BIGINT NOT NULL REFERENCES app_users, payment_order_id BIGINT REFERENCES payment_orders
);
CREATE INDEX idx_debt_events_debt ON debt_events(debt_id);
CREATE INDEX idx_debt_events_actor ON debt_events(actor_id);
CREATE INDEX idx_debt_events_payment ON debt_events(payment_order_id);
CREATE TRIGGER debt_events_append_only BEFORE UPDATE OR DELETE ON debt_events FOR EACH ROW EXECUTE FUNCTION v2_append_only();

CREATE TABLE idempotency_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    actor_id BIGINT NOT NULL REFERENCES app_users, scope TEXT NOT NULL, key TEXT NOT NULL,
    request_hash TEXT NOT NULL, status TEXT NOT NULL, resource_type TEXT, resource_id TEXT, response_snapshot JSONB,
    UNIQUE(actor_id,scope,key)
);
