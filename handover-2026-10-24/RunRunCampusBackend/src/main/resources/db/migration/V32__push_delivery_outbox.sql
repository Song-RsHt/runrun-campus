CREATE TABLE push_delivery_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL REFERENCES app_users(id),
    order_id BIGINT NOT NULL REFERENCES campus_orders(id),
    title VARCHAR(120) NOT NULL,
    content VARCHAR(300) NOT NULL,
    idempotent_token VARCHAR(64) NOT NULL UNIQUE,
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING', 'PROCESSING', 'SENT', 'DEAD')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 5),
    next_attempt_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    locked_until TIMESTAMP(6) WITH TIME ZONE,
    last_error VARCHAR(500),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    sent_at TIMESTAMP(6) WITH TIME ZONE
);

CREATE INDEX idx_push_delivery_due
    ON push_delivery_tasks (next_attempt_at, id)
    WHERE status IN ('PENDING', 'PROCESSING');
CREATE INDEX idx_push_delivery_status_created
    ON push_delivery_tasks (status, created_at DESC, id DESC);
